// Generate docs/ESTABLISHMENTS.md from data/reference/establishments.json (+ the previous list from git for the dropped/added comparison)
import { readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
const J = JSON.parse(readFileSync(new URL('../data/reference/establishments.json', import.meta.url)));
const OFF = JSON.parse(readFileSync(new URL('../data/reference/official_nadc_reporting_2026-05.json', import.meta.url)));
const E = J.establishments;
const order = ['NMHS', 'SMHS', 'EMHS', 'CAHS', 'WACHS'];
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
let OLD = [];
try { OLD = JSON.parse(execSync('git show 5a284d9:data/reference/establishments.json', { cwd: new URL('..', import.meta.url).pathname, stdio: ['ignore', 'pipe', 'ignore'] })).establishments; } catch { /* history not available */ }
const oc = new Set(OLD.map((e) => e.code)), nc = new Set(E.map((e) => e.code));
const types = {}; E.forEach((e) => { const k = e.type ? `${e.type} ${e.typeLabel}` : '(code not in the List\'s Appendix A / System Codes table)'; types[k] = (types[k] || 0) + 1; });
const inferred = E.filter((e) => e.nadcColumn === 'inferred');
const locFlag = E.filter((e) => ['not-found', 'nearest-town', 'osm-similar-name', 'shared-site', 'osm-named'].includes(e.locationStatus));
const hspNon = E.filter((e) => e.hspBasis !== 'slip');
let m = `# Establishments in the simulation: Reports to NADC = Y (official List, May 2026)

**${E.length} establishments.** The simulation's reporting sites are *exactly* the establishments with **Reports to NADC = Y** in the WA Health *Establishment List*, May 2026 (v0.1), as supplied to this project by its user. Generated by \`tools/build_establishments_doc.mjs\` from \`data/reference/establishments.json\` (built by \`tools/build_establishments.mjs\` from \`data/reference/official_nadc_reporting_2026-05.json\`). Sources are in [SOURCES.md](SOURCES.md).

## What is official and what is not

| Field | Where it comes from | Official? |
|---|---|---|
| **Code**, **Name**, **Reports to NADC = Y** | Establishment List May 2026, "Establishment List, Reporting" table | **Yes** |
| **Type** (AH, NP, OH, RC, DS ...) and **MPS** flag | Same document: the Hospital Morbidity System Codes table (Est type) and Appendix D (Multi-Purpose Services) | **Yes** (${E.filter((e) => e.type).length} of ${E.length} codes appear in that table; ${E.filter((e) => !e.type).length} do not and show "none") |
| **HSP** (Health Service Provider) | **Not in the List.** From the SLIP HEALTH-001 geographic service, with overrides from the Department of Health Central Referral Service page (see "Sites needing a note") | **No** |
| **Region, district, beds, suburb** | **Not in the List.** SLIP HEALTH-001 / HEALTH-002 | **No** |
| **Latitude / longitude** | **Not in the List.** SLIP HEALTH-001, or OpenStreetMap for the few that SLIP does not have | **No** |

* The List's Reporting table has **191 rows**; **${E.length}** are marked Reports to NADC = Y and **${191 - E.length}** are not (the document does not say where those report; earlier search extracts showed day surgeries, hospices, dialysis centres and private hospitals among them). The rows that are not flagged are *not* in the simulation and are not reproduced here.
* **How the Y flags were read (be aware).** The PDF's text layer does not keep column positions for the Read tool, so a Y cannot be assigned to the NADC column from that alone. The flags come from a column-aware text extract of the same WA Health publication, returned through a search index; its edition is not stated. Its counts were cross-checked against the user-supplied May 2026 PDF (${E.length} NADC = Y). **${inferred.length} rows are inferred** rather than read directly (marked ‡ below): ${inferred.map((e) => `${e.code} ${e.name}`).join('; ') || 'none'}. Please check those against the original.
* Where an official name differs from the SLIP name, the **official name is used**; the SLIP name is kept in the data as \`slipName\`.

## Counts

### By Health Service Provider (HSP grouping is not official)

| HSP | Name | Reporting establishments |
|---|---|---|
${order.map((h) => `| ${h} | ${J.hspNames[h]} | ${J.byHsp[h] || 0} |`).join('\n')}
| | **Total** | **${E.length}** |

### By establishment type (official)

| Type | Establishments |
|---|---|
${Object.entries(types).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}

${E.filter((e) => e.mps).length} of the ${E.length} are Multi-Purpose Services (Appendix D of the List).

## Changes against the earlier version of this list

The earlier version (round 2) had ${OLD.length} sites, taken from the SLIP "Outpatient Reporting" flag plus a partial reading of the official List. Against the official Reports to NADC = Y set:

* **Added (${E.filter((e) => !oc.has(e.code)).length}):** ${E.filter((e) => !oc.has(e.code)).map((e) => `${e.code} ${e.name}`).join('; ')}.
* **Dropped (${OLD.filter((e) => !nc.has(e.code)).length}), because they are not flagged:** ${OLD.filter((e) => !nc.has(e.code)).map((e) => `${e.code} ${e.name}`).join('; ')}.
* Earlier discrepancy resolved: the earlier list used code 0645 for Peel Health Campus (the SLIP id); the official List uses **0145**. So 0645 → 0145 is a re-coding, not a real drop and add: the net change is 11 dropped, 19 added, 1 re-coded.
* Official names replace SLIP names for ${OLD.filter((e) => nc.has(e.code) && E.find((x) => x.code === e.code).name !== e.name).length} sites.

## Sites needing a note
`;
for (const e of E.filter((e) => e.hspNote)) m += `\n* **${e.code} ${e.name}** (${e.hsp}): ${e.hspNote}`;
m += `

### Positions that are approximate (${locFlag.length})

`;
for (const e of locFlag) m += `* **${e.code} ${e.name}** (${e.locationStatus}): ${e.locationNote || ''}\n`;
m += `
Sites that **could not be located** (placeholder dot at Perth CBD, flagged ⚑ in the app): ${E.filter((e) => e.locationStatus === 'not-found').map((e) => `${e.code} ${e.name}`).join('; ') || 'none'}. Position statuses overall: ${Object.entries(E.reduce((a, e) => ((a[e.locationStatus] = (a[e.locationStatus] || 0) + 1), a), {})).map(([k, v]) => `${k} ${v}`).join(', ')}.

### HSP not taken from SLIP (${hspNon.length}; marked * below)

${hspNon.map((e) => `${e.code} ${e.short} (${e.hsp}, ${e.hspBasis})`).join('; ')}. \`crs\` = from the Department of Health Central Referral Service page; \`assumed\` = display grouping only, because the documents do not say.

`;
for (const h of order) {
  const rows = E.filter((e) => e.hsp === h);
  m += `## ${h}: ${J.hspNames[h]} (${rows.length})\n\n| Code | Official name | Type | MPS | Region | District | Beds | Lat | Long | Position | HSP basis |\n|---|---|---|---|---|---|---|---|---|---|---|\n`;
  for (const e of rows) m += `| ${e.code}${e.nadcColumn === 'inferred' ? ' ‡' : ''} | ${esc(e.name)}${e.contracted ? ' (contracted)' : ''} | ${e.type ? e.type : 'none'} | ${e.mps ? 'Y' : ''} | ${esc(e.region)} | ${esc(e.district)} | ${e.beds || '–'} | ${e.lat?.toFixed?.(4) ?? ''} | ${e.lon?.toFixed?.(4) ?? ''} | ${e.locationStatus} | ${e.hspBasis}${e.hspBasis !== 'slip' ? '*' : ''} |\n`;
  m += '\n';
}
m += `## Known gaps

* **No HSP, region or coordinates in the official List.** All three are this project's joins (SLIP HEALTH-001/-002, OpenStreetMap, the Central Referral Service page). The data custodian can replace them.
* ${inferred.length} Reports-to-NADC marks are inferred (‡), see above.
* ${locFlag.length} positions are approximate or assumed; ${E.filter((e) => e.locationStatus === 'not-found').length} sites cannot be located.
* The documents do not say why private hospitals (e.g. 602, 612, 629, 6007), the Silver Chain Hospital at Home (652) or non-hospital organisations (4275, 4506) report to the NADC. See [OPEN-QUESTIONS.md](OPEN-QUESTIONS.md).
* Attribution: ${J._attribution}
`;
writeFileSync(new URL('../docs/ESTABLISHMENTS.md', import.meta.url), m);
console.log('ok', m.length);
