// Generate docs/ESTABLISHMENTS.md from data/reference/establishments.json
import { readFileSync, writeFileSync } from 'node:fs';
const J = JSON.parse(readFileSync(new URL('../data/reference/establishments.json', import.meta.url)));
const E = J.establishments;
const order = ['EMHS', 'NMHS', 'SMHS', 'CAHS', 'WACHS'];
const esc = s => String(s ?? '').replace(/\|/g, '\\|');
let m = `# Establishments flagged as outpatient-reporting

**${E.length} establishments** (${E.filter(e => e.kind === 'hospital').length} hospitals and ${E.filter(e => e.kind === 'nursing_post').length} nursing posts). Generated by \`tools/build_establishments_doc.mjs\` from \`data/reference/establishments.json\`. Retrieved ${J._retrieved}.

## What this list is, and is not

* It is the set of sites that the Department of Health spatial dataset **HEALTH-001 "Health Hospitals"** flags **"Outpatient Reporting" = Y** (SLIP public service, layers 7 and 6).
* It is **not** a certified list of NADC reporting establishments. The official Establishments list PDF could not be retrieved, and HEALTH-001 does not define the flag. Whether it means "reports to the Non-Admitted Data Collection" is the first open question in [OPEN-QUESTIONS.md](OPEN-QUESTIONS.md).
* **Code** is the HEALTH-001 \`estab_id\` padded to four digits. That it equals the NADC *Establishment Code* is an assumption (see [SOURCES.md](SOURCES.md) 4.1).
* **HSP** (Health Service Provider) comes from HEALTH-001's geographic service, with the overrides in the notes below (checked against the Department of Health Central Referral Service page, last reviewed 8 Sep 2026, and the cited sources).
* **Region and district** are the HEALTH-001 / HEALTH-002 assignments. For example, the "City" district is in East Metro and "Lower West" (which contains Sir Charles Gairdner Hospital) is in North Metro. This follows SLIP and may differ from the HSP catchment a clinician would name.
* **Lat/long** are the HEALTH-001 coordinates (decimal degrees; the datum is not stated in the layer description).
* **Beds** are HEALTH-001 "No. of beds" (0 means not recorded, for example Hedland).
* **Contracted** marks sites run by a non-government operator on behalf of the State.
* All data: ${J._attribution}

## Count by Health Service Provider

| HSP | Name | Establishments |
|---|---|---|
${order.map(h => `| ${h} | ${J.hspNames[h]} | ${J.byHsp[h] || 0} |`).join('\n')}

## Sites needing a note
`;
for (const e of E.filter(e => e.hspNote)) m += `\n* **${e.code} ${e.name}** (${e.hsp}): ${e.hspNote}`;
m += '\n\n';
for (const h of order) {
  const rows = E.filter(e => e.hsp === h);
  m += `## ${h}: ${J.hspNames[h]} (${rows.length})\n\n| Code | Name | Type | Category | Region | District | Suburb | Beds | Lat | Long | Contracted | Source |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
  for (const e of rows) m += `| ${e.code} | ${esc(e.name)} | ${e.kind === 'hospital' ? 'Hospital' : 'Nursing post'} | ${esc(e.category)} | ${esc(e.region)} | ${esc(e.district)} | ${esc(e.suburb)} | ${e.beds || '–'} | ${e.lat} | ${e.lon} | ${e.contracted ? 'Yes' : ''} | HEALTH-001 layer ${e.slipLayer}, id ${e.slipObjectId} |\n`;
  m += '\n';
}
m += `## Known gaps

* Sites that may report to the NADC but are not flagged in HEALTH-001 (for example Child and Adolescent Health Service community sites, Graylands, Selby, Next Step, and the Byford Health Hub that the EMHS website lists) are **not** in this list. Whether they report is an open question.
* The site list reflects HEALTH-001 as retrieved on ${J._retrieved}. The Department's own current Establishments list should replace it.
* A Women, Babies and Children HSP is planned from July 2027 (one source, medium confidence). It is not modelled.
`;
writeFileSync(new URL('../docs/ESTABLISHMENTS.md', import.meta.url), m);
console.log('ok', m.length);
